// Circular cross-section helper for watertight CSG pipe/hose sweeps
function circleProfile(radiusMm: number, segments = 12): [number, number][] {
  const pts: [number, number][] = [];
  for (let i = 0; i < segments; i++) {
    const a = (i / segments) * Math.PI * 2;
    pts.push([Number((Math.cos(a) * radiusMm).toFixed(2)), Number((Math.sin(a) * radiusMm).toFixed(2))]);
  }
  return pts;
}

